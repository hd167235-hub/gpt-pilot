#: character -> cell index (row major)
INDEX: dict[str, int] = {}
for _i, _ch in enumerate(sorted(_GLYPHS)):
    INDEX[_ch] = _i
# The design rows are stored top-down but tiles are read with v=0 at the bottom,
# so glyph pixels are written into the atlas vertically flipped.  That way
# ``glyph_uv`` + a y-down screen quad renders upright text.
FLIP_VERTICAL = True

_REPLACEMENT = INDEX["?"]


def build_atlas() -> np.ndarray:
    """White RGBA atlas with alpha set wherever a glyph pixel is on."""
    atlas = np.zeros((ATLAS_H, ATLAS_W, 4), dtype=np.uint8)
    for ch, glyph in _GLYPHS.items():
        idx = INDEX[ch]
        cx = (idx % COLS) * CELL_W
        cy = (idx // COLS) * CELL_H
        rows = glyph.split("/")
        for row, bits in enumerate(rows):
            target_row = (GLYPH_H - 1 - row) if FLIP_VERTICAL else row
            for col, bit in enumerate(bits):
                if bit == "1":
                    atlas[cy + target_row, cx + col] = (255, 255, 255, 255)
    return atlas


def glyph_uv(ch: str) -> tuple[float, float, float, float]:
    """UV rectangle of a character's cell (v flipped for OpenGL)."""
    idx = INDEX.get(ch, _REPLACEMENT)
    cx = (idx % COLS) * CELL_W
    cy = (idx // COLS) * CELL_H
    u0 = cx / ATLAS_W
    u1 = (cx + GLYPH_W) / ATLAS_W
    v0 = 1.0 - (cy + GLYPH_H) / ATLAS_H
    v1 = 1.0 - cy / ATLAS_H
    return u0, v0, u1, v1


def text_width(text: str, scale: int = 2, spacing: int = 1) -> int:
    """Pixel width of ``text`` when drawn with the given scale."""
    if not text:
        return 0
    return len(text) * (GLYPH_W + spacing) * scale - spacing * scale


def save_png(path: str) -> None:
    """Debug helper: write the font atlas to a PNG (white on black)."""
    from PIL import Image

    atlas = build_atlas()
    img = np.zeros((ATLAS_H, ATLAS_W, 3), dtype=np.uint8)
    img[:, :, :] = atlas[:, :, 0:1]
    if FLIP_VERTICAL:
        img = img[::-1]
    Image.fromarray(img, "RGB").resize((ATLAS_W * 6, ATLAS_H * 6), Image.NEAREST).save(path)
